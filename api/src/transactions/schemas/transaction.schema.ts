import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { HydratedDocument, Schema as MongooseSchema, Types } from 'mongoose';
import type { TxType } from '../transaction-effects';

export const TX_TYPES = ['income', 'expense', 'transfer'] as const;
export const TX_SOURCES = ['manual', 'subscription', 'installment'] as const;
export type TxSource = (typeof TX_SOURCES)[number];

@Schema({ timestamps: true })
export class Transaction {
  @Prop({ type: MongooseSchema.Types.ObjectId, ref: 'User', required: true })
  userId!: Types.ObjectId;

  @Prop({ type: String, required: true, enum: TX_TYPES })
  type!: TxType;

  /** Money as integer cents, always positive; `type` gives the direction. */
  @Prop({ required: true })
  amountCents!: number;

  /** Stored in UTC. */
  @Prop({ required: true })
  date!: Date;

  /**
   * Income: receiving account. Expense: paying account (absent when paid with
   * a credit card). Transfer: origin.
   */
  @Prop({ type: MongooseSchema.Types.ObjectId, ref: 'Account' })
  accountId?: Types.ObjectId;

  /** Transfers only: destination account. */
  @Prop({ type: MongooseSchema.Types.ObjectId, ref: 'Account' })
  toAccountId?: Types.ObjectId;

  /** Expenses only: the credit card that paid (instead of an account). */
  @Prop({ type: MongooseSchema.Types.ObjectId, ref: 'CreditCard' })
  creditCardId?: Types.ObjectId;

  /** Transfers only: the credit card being paid (instead of toAccountId). */
  @Prop({ type: MongooseSchema.Types.ObjectId, ref: 'CreditCard' })
  toCreditCardId?: Types.ObjectId;

  /** Set on charges generated by a subscription (they stay editable). */
  @Prop({ type: MongooseSchema.Types.ObjectId })
  subscriptionId?: Types.ObjectId;

  /** Set when the transaction is managed by an installment purchase. */
  @Prop({ type: MongooseSchema.Types.ObjectId })
  installmentPurchaseId?: Types.ObjectId;

  @Prop({ type: MongooseSchema.Types.ObjectId, ref: 'Category' })
  categoryId?: Types.ObjectId;

  @Prop({ type: MongooseSchema.Types.ObjectId })
  subcategoryId?: Types.ObjectId;

  @Prop({ trim: true })
  note?: string;

  @Prop({ type: String, required: true, enum: TX_SOURCES, default: 'manual' })
  source!: TxSource;
}

export type TransactionDocument = HydratedDocument<Transaction>;
export const TransactionSchema = SchemaFactory.createForClass(Transaction);

TransactionSchema.index({ userId: 1, date: -1 });
TransactionSchema.index({ userId: 1, categoryId: 1 });
